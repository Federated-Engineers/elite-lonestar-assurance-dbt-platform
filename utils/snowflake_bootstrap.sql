
-- create role and user for terraform service user

USE ROLE ACCOUNTADMIN;

CREATE ROLE TERRAFORM_ROLE;

GRANT ROLE USERADMIN TO ROLE TERRAFORM_ROLE;
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE TERRAFORM_ROLE;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE TERRAFORM_ROLE;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE TERRAFORM_ROLE;
GRANT CREATE INTEGRATION ON ACCOUNT TO ROLE TERRAFORM_ROLE;

CREATE USER TERRAFORM_SERVICE
    TYPE = SERVICE
    COMMENT = "Service user for Terraforming Snowflake"
    RSA_PUBLIC_KEY = "<RSA_PUBLIC_KEY_HERE>";

GRANT ROLE TERRAFORM_ROLE TO USER TERRAFORM_SERVICE;

SELECT LOWER(current_organization_name()) as org_name,
LOWER(current_account_name()) as account_name;

GRANT ROLE TERRAFORM_ROLE TO ROLE AACCOUNTADMIN;
GRANT ROLE DBT_ROLE TO ROLE AACCOUNTADMIN;
GRANT ROLE CI_ROLE TO ROLE AACCOUNTADMIN;
